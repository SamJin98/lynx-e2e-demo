import {test,surfaceOf} from '@e2e-dev/web';
import {expect} from 'e2e';
import {engine} from '../engine.ts';
import {mkdir,writeFile} from 'node:fs/promises';

test('Agent complete product journey with continuous drag and nested scrolling',{timeout:300000,agent:'default'},async({app,browser,agent})=>{
 const page=surfaceOf(engine)!.page();
 await page.addInitScript(()=>{
  const audit={drags:[] as number[],wheels:0,paginationClicks:0};
  (window as any).__gestureAudit=audit;
  let start:number|undefined;
  const inPhoto=(e:Event)=>e.composedPath().some((n:any)=>n.classList?.contains('photo'));
  document.addEventListener('pointerdown',(e)=>{if(e.pointerType==='mouse'&&inPhoto(e))start=e.clientX;},true);
  document.addEventListener('pointerup',(e)=>{if(start!==undefined){audit.drags.push(e.clientX-start);start=undefined;}},true);
  document.addEventListener('wheel',(e)=>{if(inPhoto(e))audit.wheels++;},true);
  document.addEventListener('click',(e)=>{if(e.composedPath().some((n:any)=>n.classList?.contains('dot')))audit.paginationClicks++;},true);
 });
 await app.open('/');
 await expect(browser.locator('.title')).toHaveText('The Everyday Chair');
 await agent.act('Drag the Right side of product image onto the Left side of product image to view image 2. Use the drag tool on these two named image regions. Do not scroll and do not tap pagination.',{agent:process.env.E2E_DECISIONS === '1' ? 'gesture' : 'default',maxSteps:6,maxModelCalls:6});
 await expect(browser.locator('#image-index')).toHaveText('2 / 3');
 const gestures=await page.evaluate(()=>(window as any).__gestureAudit);
 expect(gestures.drags.some((distance:number)=>distance < -220)).toBe(true);
 expect(gestures.wheels).toBe(0);
 expect(gestures.paginationClicks).toBe(0);
 await agent.act('Scroll down the product page to Details & materials and expand it.',{maxSteps:6,maxModelCalls:6});
 await expect(browser.locator('#product-details')).toHaveText('Solid wood frame. Upholstered seat. Width 54 cm · Depth 58 cm · Height 78 cm. Wipe clean with a soft, dry cloth.');
 await agent.act('Open Frame material (Choose frame).',{maxSteps:4,maxModelCalls:4});
 await expect(browser.locator('#frame-options')).toBeVisible();
 const outerBefore=await page.locator('#product-scroll').evaluate(e=>e.scrollTop);
 await agent.act('Scroll down inside the frame options panel until Choose Walnut frame is visible. Use scroll_to for Walnut or scroll the panel. Do not select any frame yet.',{maxSteps:6,maxModelCalls:6});
 const innerTop=await page.locator('#frame-options').evaluate(e=>e.scrollTop);
 const outerAfter=await page.locator('#product-scroll').evaluate(e=>e.scrollTop);
 expect(innerTop).toBeGreaterThan(0);
 expect(outerAfter).toBe(outerBefore);
 await agent.act('Choose Walnut frame.',{maxSteps:4,maxModelCalls:4});
 await expect(browser.locator('#selected-frame')).toHaveText('Walnut ›');
 await agent.act('Select Sand finish, set quantity to 2, and Add to bag.',{maxSteps:8,maxModelCalls:8});
 await expect(browser.locator('#bag-count')).toHaveText('Bag (2)');
 await expect(browser.locator('#confirmation')).toHaveText('2 × Sand added to bag');
 await agent.act('Open Shopping bag. Increase bag quantity once so it contains 3 chairs.',{maxSteps:6,maxModelCalls:6});
 await expect(browser.locator('#cart-variant')).toHaveText('Sand / Walnut');
 await expect(browser.locator('#cart-quantity')).toHaveText('Quantity: 3');
 await expect(browser.locator('#cart-total')).toHaveText('$810');
 await mkdir('screenshots',{recursive:true});
 await page.screenshot({path:'screenshots/agent-journey-cart.png'});
 await agent.act('Remove the item from the shopping bag, then Close panel.',{maxSteps:6,maxModelCalls:6});
 await expect(browser.locator('#bag-count')).toHaveText('Bag (0)');
 await expect(browser.locator('[accessibility-label="Close panel"]')).toHaveCount(0);
 await writeFile('screenshots/agent-journey-gesture.json',JSON.stringify({...gestures,innerTop,outerBefore,outerAfter},null,2));
});
